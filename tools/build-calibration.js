// Builds data/calibration.json from the real field samples in data/samples/<site>/*.json,
// and data/samples/index.json (every sample in one file, so the page can read them when served).
// Run from the project root:   node tools/build-calibration.js
// GitHub Actions runs it by itself when a sample is pushed (.github/workflows/calibration.yml).
// The calibration rules live in js/calibration.js (shared with the page's "Probar muestras" button).
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const read = (p) => JSON.parse(fs.readFileSync(path.join(ROOT, p), 'utf8'));

globalThis.Sim = {};
for (const f of ['demand', 'geometry', 'arrivals', 'control', 'vehicles', 'metrics', 'engine', 'calibration']) {
  require(path.join(ROOT, 'js', f + '.js'));
}

const samplesDir = path.join(ROOT, 'data/samples');
const samples = {};
if (fs.existsSync(samplesDir)) {
  for (const dir of fs.readdirSync(samplesDir)) {
    const full = path.join(samplesDir, dir);
    if (!fs.statSync(full).isDirectory()) continue;
    samples[dir] = fs
      .readdirSync(full)
      .filter((f) => f.endsWith('.json'))
      .sort()
      .map((file) => {
        const text = fs.readFileSync(path.join(full, file), 'utf8');
        try {
          return { file, data: JSON.parse(text) };
        } catch (err) {
          return { file, error: err.message };
        }
      });
  }
}

const { calibration, log } = Sim.buildCalibration({
  samples,
  counts: read('data/counts.json'),
  params: read('data/parameters.json'),
  sitesConfig: read('data/osm/sites.json'),
  geometry: read('data/geometry.json'),
  dayProfile: read('data/daily-profile.json'),
});
console.log(log.join('\n'));
// In GitHub Actions every problem in a sample also shows up as a warning on the run page.
if (process.env.GITHUB_ACTIONS) {
  for (const site of Object.values(calibration.sites)) for (const p of site.problems) console.log(`::warning title=Revisar muestra (${site.site})::${p}`);
}

fs.writeFileSync(path.join(ROOT, 'data/calibration.json'), JSON.stringify(calibration, null, 2) + '\n');
const index = {
  note: 'GENERATED by tools/build-calibration.js. Every sample of data/samples/, so the page can recalculate the calibration with samples added in the browser. Do not edit by hand.',
  sites: Object.fromEntries(Object.entries(samples).map(([site, list]) => [site, list.filter((s) => s.data).map((s) => ({ file: s.file, data: s.data }))])),
};
fs.writeFileSync(path.join(samplesDir, 'index.json'), JSON.stringify(index, null, 2) + '\n');
console.log('\ndata/calibration.json y data/samples/index.json escritos. Siguiente: node tools/embed-data.js y node tools/check-calibration.js');
