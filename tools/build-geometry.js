// Builds data/geometry.json from OpenStreetMap data (data/osm/*.json) and data/osm/sites.json.
// Run from the project root:   node tools/build-geometry.js
// Coordinates are converted to meters around each ring's centroid (x = east, y = north).
// Two-way roads are split into one path per direction, shifted to the right of travel (right-hand traffic).
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const LANE_WIDTH = 3.5;
const CONTEXT_RADIUS_M = 260;
const SKIP_HIGHWAYS = new Set(['footway', 'path', 'steps', 'service', 'cycleway', 'pedestrian', 'track', 'corridor']);

const config = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/osm/sites.json'), 'utf8'));
const round = (v) => Math.round(v * 10) / 10;
const dist = (a, b) => Math.hypot(a[0] - b[0], a[1] - b[1]);
const warnings = [];

function polylineLength(p) {
  let s = 0;
  for (let i = 1; i < p.length; i++) s += dist(p[i - 1], p[i]);
  return s;
}

// Shifts a polyline to the right of its drawing direction by d meters.
function offsetRight(p, d) {
  return p.map((pt, i) => {
    const a = p[Math.max(0, i - 1)];
    const b = p[Math.min(p.length - 1, i + 1)];
    const dx = b[0] - a[0];
    const dy = b[1] - a[1];
    const len = Math.hypot(dx, dy) || 1;
    return [pt[0] + (dy / len) * d, pt[1] - (dx / len) * d];
  });
}

// Keeps the first `max` meters of a polyline.
function clipStart(p, max) {
  const out = [p[0]];
  let s = 0;
  for (let i = 1; i < p.length; i++) {
    const seg = dist(p[i - 1], p[i]);
    if (s + seg >= max) {
      const t = (max - s) / seg;
      out.push([p[i - 1][0] + (p[i][0] - p[i - 1][0]) * t, p[i - 1][1] + (p[i][1] - p[i - 1][1]) * t]);
      return out;
    }
    s += seg;
    out.push(p[i]);
  }
  return out;
}
const clipEnd = (p, max) => clipStart([...p].reverse(), max).reverse();

const geometry = {
  note: 'GENERATED by tools/build-geometry.js from OpenStreetMap data (© OpenStreetMap contributors, ODbL). Coordinates in meters around each ring centroid: x = east, y = north. To change names, lanes, chains or exit capacities edit data/osm/sites.json and regenerate. Lane counts and capacities must be checked in the field.',
  lane_width_m: LANE_WIDTH,
  active_site: config.active_site || Object.keys(config.sites)[0],
  attribution: '© OpenStreetMap contributors',
  sites: {},
};

for (const [key, site] of Object.entries(config.sites)) {
  const ways = JSON.parse(fs.readFileSync(path.join(ROOT, 'data/osm', site.source), 'utf8'));
  const byId = new Map(ways.map((w) => [w.id, w]));
  const ringWay = byId.get(site.ring_way);
  const nodes = ringWay.g.slice(0, -1); // OSM closes the ring repeating the first node
  const lat0 = nodes.reduce((s, p) => s + p[0], 0) / nodes.length;
  const lon0 = nodes.reduce((s, p) => s + p[1], 0) / nodes.length;
  const kx = 111320 * Math.cos((lat0 * Math.PI) / 180);
  const ky = 110574;
  const toM = (p) => [(p[1] - lon0) * kx, (p[0] - lat0) * ky];
  const ring = nodes.map(toM);
  const used = new Set([site.ring_way]);

  function chain(ids, lanes, label) {
    let out = [];
    let lastRawEnd = null;
    for (const signed of ids) {
      const w = byId.get(Math.abs(signed));
      if (!w) throw new Error(`${key}/${label}: way ${signed} not found in ${site.source}`);
      used.add(w.id);
      let pts = w.g.map(toM);
      if (signed < 0) pts.reverse();
      if (lastRawEnd && dist(lastRawEnd, pts[0]) > 1) warnings.push(`${key}/${label}: way ${signed} does not start where the previous one ends (${dist(lastRawEnd, pts[0]).toFixed(1)} m)`);
      lastRawEnd = pts[pts.length - 1];
      const twoWay = w.t.oneway !== 'yes';
      if (twoWay) pts = offsetRight(pts, (lanes * LANE_WIDTH) / 2);
      out = out.length ? out.concat(pts.slice(1)) : pts;
    }
    return out;
  }

  const approaches = site.approaches.map((a) => {
    const res = { id: a.id, name: a.name, entry: null, exit: null, exit_capacity_vph: a.exit_capacity_vph ?? null };
    if (a.entry) {
      const p = clipEnd(chain(a.entry, a.entry_lanes, a.id + ' entry'), config.max_entry_length_m);
      res.entry = { lanes: a.entry_lanes, osm_ways: a.entry, path: p.map((q) => q.map(round)) };
    }
    if (a.exit) {
      const p = clipStart(chain(a.exit, a.exit_lanes, a.id + ' exit'), config.max_exit_length_m);
      res.exit = { lanes: a.exit_lanes, osm_ways: a.exit, path: p.map((q) => q.map(round)) };
    }
    return res;
  });

  // Bypasses (slip roads): traffic from one approach to one exit that never enters the ring.
  const bypasses = (site.bypasses || []).map((b) => {
    const p = chain(b.ways, b.lanes || 1, b.id + ' bypass');
    return { id: b.id, name: b.name, from: b.from, to: b.to, lanes: b.lanes || 1, osm_ways: b.ways, path: p.map((q) => q.map(round)) };
  });

  // Every other nearby road is kept as drawing context (with the bridges drawn on top).
  const context = [];
  for (const w of ways) {
    if (used.has(w.id) || SKIP_HIGHWAYS.has(w.t.highway)) continue;
    const pts = w.g.map(toM);
    if (!pts.some((p) => Math.hypot(p[0], p[1]) < CONTEXT_RADIUS_M)) continue;
    const bridge = (site.context_bridges || []).includes(w.id) || w.t.bridge === 'yes';
    const lanes = Number(w.t.lanes) || (w.t.oneway === 'yes' ? 1 : 2);
    context.push({ name: w.t.name || '', kind: bridge ? 'bridge' : 'road', lanes, path: pts.map((q) => q.map(round)) });
  }
  context.sort((a, b) => (a.kind === 'bridge') - (b.kind === 'bridge'));

  const entries = approaches.filter((a) => a.entry).map((a) => a.id);
  geometry.sites[key] = {
    name: site.name,
    under_construction: site.under_construction || undefined,
    osm_ring_way: site.ring_way,
    center: { lat: +lat0.toFixed(6), lon: +lon0.toFixed(6) },
    ring_lanes: site.ring_lanes,
    ring: ring.map((q) => q.map(round)),
    approaches,
    bypasses: bypasses.length ? bypasses : undefined,
    signal_phases: site.signal_phases || null,
    context,
  };
  const radii = ring.map((p) => Math.hypot(p[0], p[1]));
  console.log(
    `${key}: ring ${polylineLength([...ring, ring[0]]).toFixed(0)} m around (radius ${Math.min(...radii).toFixed(0)}-${Math.max(...radii).toFixed(0)} m), ` +
      `${approaches.length} approaches (${entries.length} with entry), ${bypasses.length} bypass(es), ${context.length} context roads`,
  );
}

fs.writeFileSync(path.join(ROOT, 'data/geometry.json'), JSON.stringify(geometry, null, 1) + '\n');
for (const w of warnings) console.warn('WARNING: ' + w);
console.log('data/geometry.json written.');
